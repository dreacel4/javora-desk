#!/usr/bin/env node
// Generates src/lib/supabase/database.types.ts (Supabase-compatible format)
// by introspecting a Postgres database that has the migrations applied.
//
//   PGHOST=... PGPORT=... PGUSER=... PGDATABASE=... node scripts/gen-db-types.mjs
//
// With the Supabase CLI available you can instead run:
//   supabase gen types typescript --project-id <ref> > src/lib/supabase/database.types.ts
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = String.raw`
with enums as (
  select t.typname as name, json_agg(e.enumlabel order by e.enumsortorder) as values
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'
  group by t.typname
),
cols as (
  select c.table_name, c.column_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null or c.is_identity = 'YES' as has_default,
         c.data_type, c.udt_name, c.ordinal_position,
         (select t.table_type from information_schema.tables t where t.table_schema = 'public' and t.table_name = c.table_name) as table_type
  from information_schema.columns c where c.table_schema = 'public'
),
rels as (
  select tc.table_name, tc.constraint_name,
         json_agg(kcu.column_name order by kcu.ordinal_position) as columns,
         ccu.table_name as ref_table,
         json_agg(distinct ccu.column_name) as ref_columns
  from information_schema.table_constraints tc
  join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
  join information_schema.constraint_column_usage ccu on ccu.constraint_name = tc.constraint_name and ccu.table_schema = tc.table_schema
  where tc.constraint_type = 'FOREIGN KEY' and tc.table_schema = 'public'
  group by tc.table_name, tc.constraint_name, ccu.table_name
),
fns as (
  select p.proname as name,
         coalesce((select json_agg(json_build_object('name', a.name, 'type', format_type(a.type, null), 'has_default', a.ord > p.pronargs - p.pronargdefaults)
                   order by a.ord)
           from unnest(p.proargnames[1:p.pronargs], p.proargtypes::oid[]) with ordinality as a(name, type, ord)), '[]') as args,
         format_type(p.prorettype, null) as returns,
         p.proretset as returns_set,
         (select json_agg(json_build_object('name', n, 'type', format_type(t, null)) order by o)
            from unnest(p.proargnames, p.proallargtypes::oid[], p.proargmodes) with ordinality as x(n, t, m, o)
           where m = 't') as table_cols
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and has_function_privilege('authenticated', p.oid, 'execute')
    and p.prorettype <> 'trigger'::regtype
)
select json_build_object(
  'enums', (select json_object_agg(name, values) from enums),
  'cols', (select json_agg(cols order by table_name, ordinal_position) from cols),
  'rels', (select coalesce(json_agg(rels), '[]') from rels),
  'fns', (select json_agg(fns order by name) from fns)
);`;

const raw = execFileSync("psql", ["-X", "-At", "-c", sql], { encoding: "utf8" });
const { enums, cols, rels, fns } = JSON.parse(raw);

const enumRef = (udt) => (enums[udt] ? `Database["public"]["Enums"]["${udt}"]` : null);
function tsType(dataType, udt) {
  const base = udt.startsWith("_") ? udt.slice(1) : udt;
  const map = {
    uuid: "string", text: "string", varchar: "string", timestamptz: "string", timestamp: "string", date: "string",
    int2: "number", int4: "number", int8: "number", numeric: "number", float4: "number", float8: "number",
    bool: "boolean", jsonb: "Json", json: "Json", interval: "string",
  };
  const t = enumRef(base) ?? map[base] ?? "unknown";
  return udt.startsWith("_") ? `${t}[]` : t;
}
function fnType(pgType) {
  const isArray = pgType.endsWith("[]");
  const base = pgType.replace(/\[\]$/, "").replace(/^public\./, "");
  const map = {
    uuid: "string", text: "string", "timestamp with time zone": "string", integer: "number", bigint: "number",
    numeric: "number", boolean: "boolean", jsonb: "Json", void: "undefined",
  };
  const t = enumRef(base) ?? map[base] ?? "unknown";
  return isArray ? `${t}[]` : t;
}

const tables = {};
for (const c of cols) {
  (tables[c.table_name] ??= { type: c.table_type, cols: [] }).cols.push(c);
}

let out = `// AUTO-GENERATED by scripts/gen-db-types.mjs — do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
const viewsOut = [];
for (const [name, t] of Object.entries(tables).sort()) {
  const row = t.cols.map((c) => `          ${c.column_name}: ${tsType(c.data_type, c.udt_name)}${c.nullable || t.type === "VIEW" ? " | null" : ""};`).join("\n");
  const ins = t.cols.map((c) => `          ${c.column_name}${c.nullable || c.has_default ? "?" : ""}: ${tsType(c.data_type, c.udt_name)}${c.nullable ? " | null" : ""};`).join("\n");
  const upd = t.cols.map((c) => `          ${c.column_name}?: ${tsType(c.data_type, c.udt_name)}${c.nullable ? " | null" : ""};`).join("\n");
  const r = rels
    .filter((x) => x.table_name === name)
    .map((x) => `          {
            foreignKeyName: "${x.constraint_name}";
            columns: ${JSON.stringify(x.columns)};
            isOneToOne: false;
            referencedRelation: "${x.ref_table}";
            referencedColumns: ${JSON.stringify(x.ref_columns)};
          },`)
    .join("\n");
  const block = `      ${name}: {
        Row: {
${row}
        };
${t.type === "VIEW" ? "" : `        Insert: {
${ins}
        };
        Update: {
${upd}
        };
`}        Relationships: [
${r}
        ];
      };
`;
  if (t.type === "VIEW") viewsOut.push(block);
  else out += block;
}
out += `    };
    Views: {
${viewsOut.join("")}    };
    Functions: {
`;
for (const f of fns) {
  const args = f.args.filter((a) => a.name);
  const argStr = args.length
    ? `{\n${args.map((a) => `          ${a.name}${a.has_default ? "?" : ""}: ${fnType(a.type)}${a.has_default ? " | null" : ""};`).join("\n")}\n        }`
    : "Record<PropertyKey, never>";
  let ret;
  if (f.table_cols) {
    ret = `{\n${f.table_cols.map((c) => `          ${c.name}: ${fnType(c.type)};`).join("\n")}\n        }[]`;
  } else {
    ret = fnType(f.returns) + (f.returns_set ? "[]" : "");
  }
  out += `      ${f.name}: {
        Args: ${argStr};
        Returns: ${ret};
      };
`;
}
out += `    };
    Enums: {
${Object.entries(enums).sort().map(([k, v]) => `      ${k}: ${v.map((x) => JSON.stringify(x)).join(" | ")};`).join("\n")}
    };
    CompositeTypes: Record<string, never>;
  };
};

type PublicSchema = Database["public"];
type TablesAndViews = PublicSchema["Tables"] & PublicSchema["Views"];
// Same shape as the Supabase CLI helper: tables and views by name.
export type Tables<T extends keyof TablesAndViews> = TablesAndViews[T] extends { Row: infer R } ? R : never;
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

const target = process.argv[2] ?? "src/lib/supabase/database.types.ts";
writeFileSync(target, out);
console.log(`Wrote ${target}: ${Object.keys(tables).length} relations, ${fns.length} functions, ${Object.keys(enums).length} enums`);
